// To add or pass extra information to a server inside a URL, you use two standard methods: Query Parameters and Path Parameters.

// 1. Query Parameters (Filtering, Searching, & Sorting)
// Query parameters are key-value pairs added to the very end of a URL. They are ideal for filtering, sorting, or paginating data.
// The Syntax Anatomy:
// ?: A single question mark separates the main URL path from the parameters.
// =: Connects the key to its value (e.g., key=value).
// &: An ampersand connects multiple parameters together.


// 2. Path Parameters (Targeting a Specific Resource)
// Path parameters are built directly into the URL path structure itself. They are used to identify a specific item by its unique ID.