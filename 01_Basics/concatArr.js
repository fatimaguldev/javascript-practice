let primary = ['orange', 'blue', 'green', 'red', 'pink'];
let secondary = ['yellow', 'voilet', 'black'];
primary.concat(secondary); //both will merge

// output:  ["orange", "blue", "green", "red", "pink", "yellow", "voilet", "black"];

primary.reverse(); //it will reverse ['orange', 'blue', 'green', 'red', 'pink'];

// output:
// ["pink", "red", "green", "blue", "orange"];

